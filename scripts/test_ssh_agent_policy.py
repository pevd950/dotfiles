"""Exercise generated SSH policy with OpenSSH itself, without touching a real home."""
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest


SCRIPT = Path(__file__).with_name("setup-1password-dev.zsh")
ZSH = shutil.which("zsh")
SSH = shutil.which("ssh")
AGENT = "/tmp/dotfiles-test-agent.sock"
LEGACY_AGENT = "~/Library/Group Containers/2BUA8C4S2C.com.1password/t/agent.sock"
MARKER = "# Generated by dotfiles scripts/setup-1password-dev.zsh."


@unittest.skipUnless(ZSH and SSH, "zsh and OpenSSH are required")
class AgentPolicyTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.home = Path(self.temp.name)
        self.ssh_dir = self.home / ".ssh"
        self.ssh_dir.mkdir(mode=0o700)
        self.config = self.ssh_dir / "config"
        self.fragments = self.ssh_dir / "config.d"
        self.fragments.mkdir()
        self.fragment = self.fragments / "1password-agent.conf"
        self.library = self.home / "setup-functions.zsh"
        source, main, _ = SCRIPT.read_text().rpartition('\nmain "$@"')
        self.assertTrue(main, "test must remove the bootstrap entry point")
        # OpenSSH expands ~ using the account database, not the fixture HOME. Keep the
        # previous implementation's generated include inside this disposable home too.
        source = source.replace("Include ~/.ssh/config.d/1password-agent.conf",
                                f"Include {self.fragment}")
        self.library.write_text(source + "\n")
        self.env = {k: v for k, v in os.environ.items()
                    if k not in ("SSH_CONNECTION", "SSH_CLIENT", "SSH_AUTH_SOCK",
                                 "ONEPASSWORD_SETUP_DRY_RUN")}
        self.env.update(HOME=str(self.home), FIXTURE_SCRIPT=str(self.library))

    def setup_policy(self, *, installed=True, dry_run=False):
        env = dict(self.env)
        env["ONEPASSWORD_SETUP_DRY_RUN"] = str(int(dry_run))
        script = (
            'source "$FIXTURE_SCRIPT"\n'
            f'onepassword_app_installed() {{ return {0 if installed else 1}; }}\n'
            f'onepassword_agent_socket_config() {{ print -r -- "{AGENT}"; }}\n'
            f'onepassword_agent_socket_path() {{ print -r -- "{AGENT}"; }}\n'
            'ensure_ssh_config_identity_agent\n'
        )
        subprocess.run([ZSH, "-f", "-c", script], env=env, check=True,
                       text=True, capture_output=True)

    def agent_for(self, host="ordinary", **env_updates):
        env = dict(self.env, **env_updates)
        output = subprocess.run([SSH, "-G", "-F", str(self.config), host],
                                env=env, check=True, text=True,
                                capture_output=True).stdout
        return next((line.split(" ", 1)[1] for line in output.splitlines()
                     if line.startswith("identityagent ")), None)

    def old_fragment(self):
        self.fragment.write_text(
            MARKER + '\nMatch exec "test x${SSH_CONNECTION}${SSH_CLIENT} = x"\n'
            f'  IdentityAgent "{AGENT}"\nMatch all\n')

    def test_host_and_final_match_choices_survive_repeated_setup(self):
        self.config.write_text(
            "Host restricted\n  IdentityAgent none\n"
            "Host alternate\n  IdentityAgent /tmp/other.sock\n"
            "Match final host final-only\n  IdentityAgent none\n"
            "Host never-matches\n  User ignored\n")
        for _ in range(2):
            self.setup_policy()
            self.assertEqual(self.agent_for("restricted"), "none")
            self.assertEqual(self.agent_for("alternate"), "/tmp/other.sock")
            self.assertEqual(self.agent_for("final-only"), "none")
            self.assertEqual(self.agent_for(), AGENT)

    def test_scoped_legacy_agent_choice_is_preserved(self):
        self.config.write_text(
            f'Host legacy\n  IdentityAgent "{LEGACY_AGENT}"\n'
            "Host *\n")
        self.setup_policy()
        self.assertIn(f'IdentityAgent "{LEGACY_AGENT}"', self.config.read_text())
        self.assertTrue(self.agent_for("legacy").endswith("/t/agent.sock"))

    def test_user_rule_appended_after_managed_block_keeps_global_scope(self):
        for installed in (True, False):
            with self.subTest(installed=installed):
                self.config.write_text("Host never-matches\n  User ignored\n")
                self.setup_policy()
                with self.config.open("a") as config:
                    config.write("# User default added after initial setup\nIdentityAgent none\n")
                self.assertEqual(self.agent_for(), "none")
                self.setup_policy(installed=installed)
                self.assertEqual(self.agent_for(), "none")
                first = self.config.read_bytes()
                self.setup_policy(installed=installed)
                self.assertEqual(self.agent_for(), "none")
                self.assertEqual(first, self.config.read_bytes())

    def test_early_wildcard_and_multifile_includes_keep_user_policy(self):
        self.old_fragment()
        other = self.fragments / "user.conf"
        other.write_text("Host included\n  IdentityAgent none\nHost *\n")
        prefix = f'iNcLuDe="{self.fragments}/*.conf" "{other}"\n'
        self.config.write_text(prefix + "Host restricted\n  IdentityAgent none\n")
        self.setup_policy()
        self.assertEqual(self.agent_for("included"), "none")
        self.assertEqual(self.agent_for("restricted"), "none")
        self.assertEqual(self.agent_for(), AGENT)
        self.assertIn(prefix, self.config.read_text())
        self.assertFalse(self.fragment.exists())

    def test_unowned_fragment_is_not_rewritten_or_deleted(self):
        content = "Host custom\n  IdentityAgent /tmp/custom.sock\nHost *\n"
        self.fragment.write_text(content)
        self.config.write_text(f'Include "{self.fragment}"\n')
        self.setup_policy()
        self.assertEqual(self.fragment.read_text(), content)
        self.assertEqual(self.agent_for("custom"), "/tmp/custom.sock")
        self.setup_policy(installed=False)
        self.assertEqual(self.fragment.read_text(), content)
        self.assertEqual(self.agent_for("custom"), "/tmp/custom.sock")

    def test_only_local_sessions_get_fallback_and_setup_is_idempotent(self):
        self.setup_policy()
        first = self.config.read_bytes()
        self.assertEqual(self.agent_for(), AGENT)
        self.assertNotEqual(self.agent_for(SSH_CONNECTION="inbound"), AGENT)
        self.assertNotEqual(self.agent_for(SSH_CLIENT="inbound"), AGENT)
        self.setup_policy()
        self.assertEqual(first, self.config.read_bytes())

    def test_absent_app_removes_managed_policy_but_preserves_choices(self):
        self.old_fragment()
        self.config.write_text(
            f'Include "{self.fragment}"\nHost restricted\n  IdentityAgent none\n')
        self.setup_policy()
        self.setup_policy(installed=False)
        self.assertFalse(self.fragment.exists())
        self.assertEqual(self.agent_for("restricted"), "none")
        self.assertNotEqual(self.agent_for(), AGENT)

    def test_dry_run_leaves_config_and_fragment_untouched(self):
        self.old_fragment()
        self.config.write_text(f'Include "{self.fragment}"\n')
        before = {p: p.read_bytes() for p in (self.config, self.fragment)}
        self.setup_policy(dry_run=True)
        self.assertEqual(before, {p: p.read_bytes() for p in before})
        self.setup_policy(installed=False, dry_run=True)
        self.assertEqual(before, {p: p.read_bytes() for p in before})

    def test_symlinked_config_target_is_updated_in_place(self):
        target = self.home / "ssh-config"
        target.write_text("Host restricted\n  IdentityAgent none\n")
        self.config.symlink_to(target)
        self.setup_policy()
        self.assertTrue(self.config.is_symlink())
        self.assertEqual(self.agent_for("restricted"), "none")
        self.assertEqual(self.agent_for(), AGENT)


if __name__ == "__main__":
    unittest.main()
